#pragma once

#include "CoordinateTransform.h"   // Vec3 + touchToRobotMatrix

// ============================================================================
//  按钮2 姿态映射：笔杆姿态 → 机械臂目标姿态（纯函数，可单测）
// ============================================================================
//
// 【为什么要有这个文件】按钮2 的规格是四条：
//     笔杆平移 ⇒ 机械臂不动；笔尖左(右)摆 ⇒ 尖端向 −X(+X) 倾；
//     笔尖前(后)摆 ⇒ 尖端向 +Y(−Y) 倾；笔杆自转 ⇒ J6 转。
//   旧实现把「笔杆 Euler 角之差」【当成旋转向量】用（robot_dR = M·(drx,dry,drz)），
//   再把三个角【逐分量加到】按下时的参照姿态上。两者都只在小角度下近似成立，
//   而实际摆幅 ±50~80°、且本机末端姿态常年贴着 rx≈±180（RPY 表示的接缝）。
//
// ---- 推导表（本计划的依据；用坐标变换矩阵 M 逐行反推并验算过）----
// Touch 标准器件系 = X 右 / Y 上 / Z 朝用户；M（relay/CoordinateTransform.h 的
// touchToRobotMatrix）给出 robot = M·dev ⇒
//     dev +X → robot +X · dev +Y → robot +Z · dev +Z → robot −Y。
// 笔尖指 dev −Y（笔朝下）⇒ 用 M 反推每次"物理摆动"在基座系里是绕哪根轴：
//
// | 物理动作 | 器件系旋转 | 基座系旋转 | 体现在器件 Euler 上 |
// |---|---|---|---|
// | 笔尖左摆（尖端向 −X） | 绕 −Z | 绕 +Y | `sz` 减小 |
// | 笔尖右摆（尖端向 +X） | 绕 +Z | 绕 −Y | `sz` 增大 |
// | 笔尖前摆（尖端向 +Y） | 绕 +X | 绕 +X | `sx` 增大 |
// | 笔尖后摆（尖端向 −Y） | 绕 −X | 绕 −X | `sx` 减小 |
// | 笔杆自转 | 绕 ±Y | 绕 ±Z | `sy` ± |
//
// ★ 这张表与现有硬编码矩阵【逐行一致】（robot_dRx=+drx / robot_dRy=−drz /
//   robot_dRz=+dry 正好就是 ω_robot = M·ω_dev 的三行）⇒ **错的不在"表"，在"算术"**。
//   所以本文件【不动】M 的任何一项，也不动任何符号。
//
// ⚠ 调用约定：三个入参都是【度】；返回值也是【度】。参照姿态 refRobotRpy 是按下
//   按钮2 那一刻的机械臂 GetPose 的 Rx/Ry/Rz，与 TcpCalibration::rpyToMatrix 的
//   约定一致（R = Rz·Ry·Rx）。
// ⚠ 本函数【没有位置入参】：平移分量在结构上就进不来，这是"笔杆平移时机械臂不动"
//   的第一道保证（第二道在 RelayCore 的姿态块里）。
//
// ★★ 2026-09-23（Task 3 评审 Important）**返回值在【表示上】按 `refRobotRpy` 就近取代表**：
//   三个角各自取 `refRobotRpy[i] + 360k` 里离参照最近的那一个（`R = Rz·Ry·Rx` 下单个角
//   ±360k 不改变矩阵 ⇒ **还是同一个旋转**，只是换了一组等价代表）。
//   ⇒ 调用方可以放心地把返回值与**参照**逐分量相减：差永远是"这一段手动的量"，**不会**
//     因为跨过 ±180 接缝而变成 ±360°（本机末端常年贴着 rx≈±180 ⇒ 那是常驻工作点）。
//   ⇒ 反面约束（**实现时别再引入**）：本函数**不得**返回"穿到接缝另一边再规范化回来"的值 ——
//     那个数值跳会被控制器照字面解释成 J6 转一整圈（09-22 现场撞出的关节超速，
//     见 `Config::ORIENT_SEAM_FIX_ENABLED`）。解法是"避免穿过接缝"，不是"穿过去再表示回来"。
//   守卫：tests/test_button2_mapping.cpp ⑬。
//
// ⚠⚠ 2026-09-23（Task 3 记账）**本函数只用【兜底】那张表 M，标定路径未接**。
//   `CoordinateTransform.h:48-49` 明写"`Calibration::enabled` 为真时调用者要自己分支"，
//   而本函数既没有分支、也【不打算】在这里分支：
//     · 它拿不到标定那份的语义 —— `Calibration::R` 是"含平移的 4×4 里的 3×3 旋转块"
//       （见 convertTouchToRobot），要接就得由调用者把旋转块传进来；
//     · 而 RelayCore 的调用形状被设计定成**三参数**（计划 Task 3 设计决定 3，理由是
//       显式拷贝、不给 Vec3 成员连续性任何前提）⇒ 接标定 = 改接口 = 新设计，不是本任务。
//   **代价（已知欠账，不是"未发现的问题"）**：若 `calibration.json` 存在
//   （`Calibration::enabled = true`，由 main.cpp 的标定流程也可在运行中置真），平移路径走
//   标定出来的 R/t，姿态路径仍走兜底 M ⇒ **两条路静默不一致**。
//   ⇒ 接线处（RelayCore 的新路径）加了一条**一次性告警**（`[Orient] Calibration is enabled
//     but ...`）来把它从"静默"变成"响一次"。
//   ⇒ 要还这笔账：给本函数加一个 M 入参（或一个重载），由调用者按 `Calibration::enabled`
//     选表，并**验**（单测 + 上机）"标定之后姿态仍对"。
//
// ⚠ NaN/Inf 契约：三个入参【任一】非有限 ⇒ 返回 `refRobotRpy`（="不倾斜"，退回按下时的姿态）。
//   ⚠ 但**若 refRobotRpy 自己非有限，本函数会把那个非有限值原样返回** —— 它【不】保证
//     "返回值一定有限"。这时没有安全的兜底可退（0 是一个真实姿态，机械臂会真的转过去），
//     那一层只能由调用者负责：RelayCore 的 `m_orientRefRobot` 抄自实际姿态，它若已经是 NaN，
//     新旧两条路径都会把 NaN 传下去。该行为有用例钉住（test_button2_mapping.cpp ⑫ 覆盖三个入参位置）。
Vec3 button2OrientationTarget(const double refRobotRpy[3],
                              const double refStylusRpy[3],
                              const double curStylusRpy[3]);
