// ============================================================================
//  按钮2 关节空间映射：笔杆姿态增量 → 关节增量（纯函数，可单测）
// ============================================================================
//
// 【规格四条（本方案的全部）】
//     笔杆前后摆 ⇒ J4 · 笔杆左右摆 ⇒ J5 · 笔杆自转 ⇒ J6；
//     J1/J2/J3 逐位保持按下按钮2那一刻的值；笔杆平移 ⇒ 六个关节全不动。
//
// 【为什么绕开末端 RPY（计划 Goal 那一节，抄在这里免得下一个人再走一遍）】
//   本机末端姿态常年贴着 RPY 的**表示接缝与奇点**（实测 `|rx| > 170` 占 85.8%、
//   `ry` 常在 −66~−90）⇒ 旧路（`button2OrientationTarget`，Rz·Ry·Rx 真旋转合成 + 提取 RPY）
//   不得不带上 `clampOrientToBounds` / 逐分量限幅 / 跨接缝回避那一整套 —— 而 2026-09-22
//   那次**关节超速**正是出在那一层（控制器**不**把 RPY 当模 360，`180 → −179.9` 的数值跳
//   被照字面解释成 J6 转一整圈，见 `Config::ORIENT_SEAM_FIX_ENABLED`）。
//   ⇒ 关节空间里**没有接缝、没有奇点、不需要 IK**：整层被绕开了。
//   ⚠ 旧路**不删**（`Config::BTN2_JOINT_SPACE_ENABLED=false` 时逐字走它）—— 它也是
//     "为什么不能那么做"的记录。
//
// ---- 映射是【标定结论】，2026-09-24 换了口径：源轴 = 【器件系的三根真实旋转轴】 ----
//   ★ 现在的映射（与 `Button2Joint.cpp` 逐行一致）：
//       器件 **X**（前后摆）⇒ **J4** · 器件 **Y**（左右摆）⇒ **J5** · 器件 **Z**（自转）⇒ **J6**
//   【实测来源】2026-09-23/24 现场，操作员按顺序做三个动作、`P|` 按 30 Hz 全量落盘 ⇒
//     把笔杆姿态还原成 R 后取**逐帧增量**的旋转向量，其轴在器件系里：
//       自转   ≈ (+0.10, −0.01, +0.99)（11 个 2 秒桶一致，偏名义 Z 轴 6~12°）
//       前后摆 ≈ (+1.00, +0.08, +0.04)（偏名义 X 轴 5°）
//       左右摆 ≈ (+0.16, +0.98, +0.08)（偏名义 Y 轴 10°）
//     三根轴两两夹角 74~83°（近似正交 ✓）。
//   ⚠ 从前这里写的是"前后摆⇒Rx · 左右摆⇒Rz · 自转⇒Ry"，那是**主导欧拉角**的口径 ——
//     它已经被推翻：ZYX 欧拉角在倾斜姿态下三个分量会一起变，用它当"哪根轴在动"会串到三路
//     （实测自转 10° 被送成 J4 +1.52 / J5 +5.48 / J6 +8.50）。**别再按欧拉轴读这张表。**
//   ⚠ 三根轴**只偏名义轴 6~13°** ⇒ 按命名轴分解就够用（邻轴漏 sin(10°)≈0.17，而旧口径是 3.75）。
//     真要更准就得把笔杆装夹的姿态也标出来 —— 那是另一件事，**现在不做**。
//   ⚠ "该往哪边转"（正负）与比例是另一半：三个 `Config::BTN2_J*_SIGN` 表达它；本文件与它的
//     用例里【任何地方都不许把 +1 写死】—— 用例的期望值也必须经这三个常数表达，否则一改符号
//     就满堂红（那是测试的错，不是实现的错）。
//
// ---- 入参数组次序（★ Task 2 接线前【先读这一行】）----
//     `refStylus` / `curStylus` = **{Rx, Ry, Rz}** —— 即 `appState.stylusOrient` 的
//     (x, y, z) 三个分量（度）。出处：`core/AppState.h` 的字段注释
//     「笔杆姿态 ZYX Euler (Rx,Ry,Rz in degrees)」+ `haptic/HapticCallback.cpp` 的
//     `[0]=rx_deg · [1]=ry_deg · [2]=rz_deg` 三行赋值。
//     ⚠ 次序**不是** J4/J5/J6 的次序、也不是"按名字首字母"，而下面的映射是**错开**的
//       （out[3]←[0] · out[4]←[2] · out[5]←[1]）⇒ **本接口对索引敏感**。灌错次序的
//       后果是"前后摆变成了左右摆"，而**结构层用例①(b)(c) 会红**（它们就是为此写的）。
//
// ---- 管线 ----
//     R_ref = TcpCalibration::rpyToMatrix(refStylus)     （ZYX，输入为度）
//     R_cur = TcpCalibration::rpyToMatrix(curStylus)
//     ΔR    = R_ref^T · R_cur          【体系】增量 ⇒ 轴表达在**器件系**
//     rv    = 旋转向量(ΔR)             （方向×角，度；|rv| ≤ 180）
//   ① 逐轴死区   |rv_i| >= `Config::ORIENT_DEADZONE_DEG` 才放行，否则该轴归 0
//   ② 逐轴符号   rv_i 乘 `Config::BTN2_J*_SIGN`
//   ③ 偏移限幅   关节增量**逐关节**夹到 ±`Config::ORIENT_MAX_OFFSET_DEG`
//   ④ 一一对应   加到参照上：out[3] ← rv.x · out[4] ← rv.y · out[5] ← rv.z
