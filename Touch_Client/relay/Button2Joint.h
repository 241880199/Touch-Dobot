// ============================================================================
//  按钮2 腕部求解（2026-09-29 Task 3：3×3 角雅可比 + FK 回代 + 阻尼最小二乘）
// ============================================================================
// 解 J4/J5/J6，使 FK_R(ref[0..2], q) == targetR：
//   成功 ⇒ true，且写 `out[0..2] = ref[0..2]`、`out[3..5] = q`（**只解腕，J1/J2/J3 逐位不动**）；
//   失败（不收敛 / 雅可比退化）⇒ false，且 `out` **逐位退回 `ref`**（调用方据此判"没动"）。
// `ref` / `out`：六个关节角（度）。`targetR`：行主序 3×3 目标末端旋转（`R[r*3+c]`，与 Kinematics
//   的 `T[i][j]` 同一约定）。`maxStepDeg`：**迭代步长上限（度/轮）**，由调用方传入（不读 Config）
//   —— 与 `clampJointStep` 同一个理由：编译期常数在运行期改不了 ⇒ 写不出有牙齿的用例。
//
// 【算法】逐行见 `Button2Joint.cpp` 的 `button2SolveWrist` 实现那段注释。要点：
//   · 每轮重算 FK 与**角雅可比** `Jw[i][j] = J[3+i][3+j]`（Kinematics.cpp 的雅可比行 3..5 =
//     各关节 z 轴，列 3..5 = 腕三个关节 ⇒ 正好是"腕关节 → 世界系角速度"那 3×3 块）；
//   · 误差 `e = rotVecDeg(targetR · Rqᵀ)`（**世界系**，度）—— 与 `Rqᵀ` 右乘 ⇒ e 是"把当前转到
//     目标还要在世界系里绕的那一下"；
//   · 阻尼最小二乘 `dq = Jwᵀ (Jw·Jwᵀ + λ²I)⁻¹ e`，λ 自适应（收敛则减半、变差则加倍，夹在
//     `[1e-6, 1.0]`），初值 `Config::BTN2_WRIST_DAMP`；`Jw·Jwᵀ + λ²I` 奇异 ⇒ 返回 false；
//   · 逐轴把 dq 夹到 ±`maxStepDeg` 再累加；迭代 ≤ `Config::BTN2_WRIST_MAX_ITER`；
//   · 收敛门限 `Config::BTN2_WRIST_TOL_DEG`（度），**末尾无条件再自验一次**（收敛门会随漂移漏
//     判，自验是"返回 true ⇒ 真的到得了"这条不变量**唯一**的执行点）。
//     ⚠ 2026-09-29 Task 3 复审 M-2：这句里的"**无条件**"以前与代码不符（那时代码是
//       `if (!converged) { 自验 }`）⇒ 已按本条措辞把**代码**改成真·无条件（不是把这句话改小）。
//       现在两个分支（循环里判收敛而 break / 跑满 `MAX_ITER` 掉出来）都经末尾这一处判定 ⇒
//       "唯一执行点"这句也为真。⚠ 别把 `if` 加回去 —— 那会让判据分裂成两处（见 .cpp 那段）。
// ⚠ **不赌球腕**：用 FK 回代，不用闭式欧拉分解 ⇒ 腕部几何将来改了不用重推。这也意味着
//   **本函数对 `Kinematics` 的 FK/雅可比是否与该机的几何一致**这件事**照单全收**
//   （它只保证"在这个模型里解得到"）。模型若与实机不符，那是另一笔账。
// ⚠ 单位全程【度】、行主序（与上面两个函数同一约定）。
bool button2SolveWrist(const double ref[6], const double targetR[9], double maxStepDeg, double out[6]);

// ============================================================================
//  按钮2 对外入口（2026-09-29 Task 4）：Task 2 的目标朝向 + Task 3 的腕部求解 拼成一句
// ============================================================================
// 【这一步只做"拼"】它不引入任何新的数学：参照姿态、想要的末端朝向、腕部求解三件都在上面
//   各自成篇。这里的三句就是把它们串起来，加上两条**与旧函数逐条对齐**的契约。
//
// 【流水线（三句）】
//   ① `out[0..2] = ref[0..2]` —— **无条件、第一句就写**，下面**任何分支都不许再碰**这三个
//      下标。本方案的"J1/J2/J3 保持"就是这三行（与 `button2JointTarget` 同一条纪律）。
//   ② 笔杆任一分量 NaN/Inf ⇒ **六位全回参照**（与 `button2JointTarget` 的守卫逐条对齐）。
//   ③ 否则：`refR = FK(refJoints)` 的旋转部分当参照姿态 → `button2OrientTarget`（Task 2）
//      算出想要的末端朝向 → `button2SolveWrist`（Task 3）解 J4/J5/J6；
//      **求解失败 ⇒ 六位全回参照**（"本帧不下发"的形状，与 RelayCore 里 I1/I2/FK 那三处同款）。
//
// 【四入参里没有位置分量】平移在**结构上**进不来 —— 这是**编译期**性质（同 `button2JointTarget`），
//   运行期测不出来 ⇒ 由 test_button2_joint.cpp ㉕(c) 用**函数指针类型**钉住（签名一变就编译不过）。
//
// 【步长与累加器的分工】本函数把 `Config::ORIENT_MAX_STEP_DEG` 传进 Task 3 的**迭代**限幅
//   （每轮 `dq` 的步长上限）；**逐帧累加器仍由调用方 `clampJointStep` 持有**（Task 5 接线）。
//   本函数**不**做逐帧限幅 —— 同一件事写两处就会两处各自漂移。
//
// ⚠★ 【本函数直接读 `Config::BTN2_TILT_PHI_DEG`，这与 `button2OrientTarget` 把 `phiDeg` 做成
//   **入参**并不矛盾】把 φ 做成入参是为了让 Task 2 自己的用例能写"φ≠0 时行为确实变了"（⑳d）；
//   而本函数是**接线层的对外形状**，它就该读那个常数（Task 5 的调用点读的是同一个）。
//   ⇒ 想验 φ 的用例请直接测 `button2OrientTarget`（那里 φ 可传），
//     **不要**为了"能测 φ"给本函数加参数（那会把对外形状改歪，而收益为零）。
//
// ⚠ 【`refJoints` 非有限 ⇒ 本函数**原样传出去**】与 `button2JointTarget` 逐字相同：那一刻没有
//   安全的兜底可退（0 是一个**真实**关节角，机械臂会真的转过去）—— 守卫只守**笔杆侧**，
//   **不**保证返回值一定有限。这一层由调用方负责（`refJoints` 抄自 `app.robotActualPose.j1..j6`）。
void button2OrientJointTarget(const double refJoints[6], const double refStylus[3],
                              const double curStylus[3], double outJoints[6]);

// ============================================================================
//  接线层的两条纯判据（2026-09-23 Task 2 修复轮：从 RelayCore.cpp **抽出来**）
// ============================================================================
//
// 【为什么要抽】`RelayCore.cpp` **不被任何测试编译** ⇒ 修复轮（复审 1×Critical + 3×Important
//   + 2×Minor）新加的三条判据**一条自动化用例都没有**，只能靠人读 + 上机。而其中两条
//   **本来就是纯算术**（不碰 Win32、不碰 socket、不碰 appState）⇒ 抽到这里，由
//   `tests/test_button2_joint.cpp` 直接喂入参。本文件就是"这条逻辑的受测之家"。
//
// ⚠⚠ 【这一抽**不改变**任何行为，也**不改变**"接线有没有接对"的可验证性】
//   1) 判据、次序、夹取方向、累加点**逐字照抄**原处（见各自的注释与用例）；
//   2) **控制流留在调用方**：三处 `return`（本帧不下发）是流程不是算术 ⇒ 抽出来的只有算术；
//   3) 接线层（`RelayCore.cpp` 里"什么时候调、返回值怎么用"）**仍然没有自动化用例** ⇒
//      仍然只能靠人读 + 上机。**别把"这两条有单测了"读成"接线接对了"** —— 那是两件事。
//
// ⚠ 【依赖变了，必须记账】`isTrustworthyJointRef` 要用 `Kinematics::isWithinJointLimits`
//   ⇒ `Button2Joint.cpp` 现在 `#include "../robot/Kinematics.h"`，而那条链会走到
//   `CoordinateTransform.h` → `<HDU/hduVector.h>` ⇒ **`tests/build_button2_joint_test.bat`
//   从"不需要任何 /I 路径"变成需要 OpenHaptics 那两个 /I，并且要多链接
//   `../robot/Kinematics.cpp`**。那是本次抽取的唯一代价，写在那个 .bat 的注释里（原注释
//   曾断言"本套件不需要 /I" —— 那句现在**是错的**，已就地订正，没有留下）。**函数本身仍然纯**
//   （Kinematics 的 FK/IK 也是纯算术），变的只是**构建图的形状**。

// 参照可信度（复审 I1）：六位**恰好**全 0 **或** 越关节限位 ⇒ 不可信（返回 false）。
//   【场景】`app.robotActualPose.j1..j6` 的初值**全 0**，唯一写入点是 `queryJointAngles` 里
//     `FeedbackParser::parseAngle` 的**成功路径** ⇒ 若 `GetAngle()` 从未解析成功，参照就一直是
//     全 0 ⇒ FK(0,…,0) = (0, −233.3, 756) **过得了位置门** ⇒ `ServoJ(0,…,0)` 会把臂开向模型零位。
//   ⚠ 两个子句**都保留**（少任何一个都会漏掉一整类）：全 0 是"`GetAngle()` 从未成功"的指纹
//     （真机关节零点不会同时精确落在 0.0000），越限位是另一个独立的坏值形态。
//   ⚠⚠ **NaN 不在本函数的覆盖面内，而且是刻意的**：NaN 进 `isWithinJointLimits` 时逐条比较
//     全为 false ⇒ 它**返回 true**（放行）；而"恰好全 0"对 NaN 也为假 ⇒ 本函数对 NaN
//     **返回 true（可信）**。接住 NaN 的是调用方的 **FK 门**（FK(NaN) ⇒ NaN ⇒ 位置入口的
//     第一道守卫 REJECT）—— 那条不在本函数职责内。**这个边界被用例⑬逐字钉住**（断言的
//     是**现状**，且是**刻意**的现状）：别"顺手修好"它 —— 那会是一次**没有负对照**的行为改变。
bool isTrustworthyJointRef(const double ref[6]);

// 逐轴步长限幅（复审 M2）：`out[i] = prev[i] + clamp(desired[i] − prev[i], ±maxStep)`。
//   【形状是从 RPY 路径照抄的】那条路的 `ORIENT_MAX_STEP_DEG` 注释就写着"手一甩不甩飞机器人"；
//     关节路径原来是**没有**这一道 ⇒ 手一甩本帧目标可能一步跨出 ~17.5°（30 Hz ⇒ 525°/s）。
//   ★ 2026-09-23 整支终审 (F)：本函数界住的是**逐帧**增量 —— 别把"夹住了"读成"整条链有界"。
//     调用方（`RelayCore::sendPosition`）的积分器在**发送失败时照旧推进** ⇒ 连丢 k 帧则它领先
//     实际发送 k×maxStep，恢复发送的那一步可以大 k 倍（3°/帧 × 30 Hz 那句"≈90°/s"同样
//     只界"逐帧"、**不界**"恢复的那一步"）。**每帧有界、连续丢包数无界**（订正见调用方那行注释）。
//     ⚠ 这条性质**不在本函数职责内**（本函数无状态、`prev` 由调用方给），写在这里只为别让
//       读契约的人把"这一步夹住了"读成"这条链有界"。
//   ⚠ 夹的是"**本帧要走的量**"再**累加**，不是"把目标夹到 `prev ± maxStep` 就完事" ——
//     两者**逐帧结果相同**，区别在**累加器**：它是"上一帧**已下发**的目标"，由调用方持有
//     （本函数**无状态**：`prev` 由调用方传进来）。大偏移因此在多帧里**慢慢跟上**、
//     **不会被永久截断** —— RPY 路径 2026-09-21 那次改造就是为这个（`Config.h` 里
//     `ORIENT_DEADZONE_DEG` 的历史段）。
//   ⚠ **`out` 允许与 `desired` 同一块内存**（调用方就是原地改写 `j`）：逐轴**先读后写**、
//     每轴只碰自己那一个下标 ⇒ 别名安全。用例⑯(c) 把这个用法钉住。
//   ⚠ NaN：`NaN > maxStep` 与 `NaN < −maxStep` **都为假** ⇒ NaN **原样穿过**（与抽出前逐字
//     一致）。那**不是**本函数该管的事 —— 接住它的是调用方的 FK 门（同 `button2JointTarget`
//     的入参契约）。**别在这里加 isfinite 守卫**：那会是一次没有用例背书的行为改变。
//   ⚠ `maxStep` 传负数是**未定义意图**，本函数**逐字照抄**原写法（先比 `> maxStep`、
//     再比 `< −maxStep`）：负值下先被赋 `maxStep`、再被赋 `−maxStep` ⇒ 结果 = |maxStep|。
//     荒谬，但**与原处一致** —— 没有"顺手修正"（修正就是行为改变，且没有用例会红）。
//     调用方传的是 `Config::ORIENT_MAX_STEP_DEG`。
void clampJointStep(const double prev[6], const double desired[6], double maxStep, double out[6]);
