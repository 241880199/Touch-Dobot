// ============================================================================
//  按钮2 关节空间映射：笔杆姿态增量 → 关节增量（纯函数，可单测）
// ============================================================================
//
// 【规格四条（本方案的全部）】
//     笔杆前后摆 ⇒ J4 · 笔杆左右摆 ⇒ J5 · 笔杆自转 ⇒ J6；
//     J1/J2/J3 逐位保持按下按钮2那一刻的值；笔杆平移 ⇒ 六个关节全不动。
//
// 【为什么绕开末端 RPY（计划 Goal 那一节，抄在这里免得下一个人再走一遍）】
//   本机末端姿态常年贴着 RPY 的**表示接缝与奇点**（实测 `|rx| > 170` 占 85.8%、
//   `ry` 常在 −66~−90）⇒ 旧路（`button2OrientationTarget`，Rz·Ry·Rx 真旋转合成 + 提取 RPY）
//   不得不带上 `clampOrientToBounds` / 逐分量限幅 / 跨接缝回避那一整套 —— 而 2026-09-22
//   那次**关节超速**正是出在那一层（控制器**不**把 RPY 当模 360，`180 → −179.9` 的数值跳
//   被照字面解释成 J6 转一整圈，见 `Config::ORIENT_SEAM_FIX_ENABLED`）。
//   ⇒ 关节空间里**没有接缝、没有奇点、不需要 IK**：整层被绕开了。
//   ⚠ 旧路**不删**（`Config::BTN2_JOINT_SPACE_ENABLED=false` 时逐字走它）—— 它也是
//     "为什么不能那么做"的记录。
//
// ---- 三条映射是【标定结论】，不是推导 ----
//   源侧已【实测】（2026-09-23 晚，操作员摆三个姿势、按 SPACE、机械臂不动、读笔杆欧拉角）：
//     前后摆 ⇒ 笔杆 **Rx**（主导 +20.3°）⇒ **J4**
//     左右摆 ⇒ 笔杆 **Rz**（主导 −34.7°）⇒ **J5**
//     自转   ⇒ 笔杆 **Ry**              ⇒ **J6**
//   ⚠ 那一刻量到的是"**哪根轴在动**"。"该往哪边转"（正负）与比例**都还没量过** ⇒
//     逐轴符号单独提成 `Config::BTN2_J4_SIGN / BTN2_J5_SIGN / BTN2_J6_SIGN`（默认 +1），
//     由计划 Task 3 上机实测钉死。
//     ⚠ 因此本文件与它的用例里【任何地方都不许把 +1 写死】—— 用例的期望值也必须经这三个
//       常数表达，否则 Task 3 一改符号就满堂红（那是测试的错，不是实现的错）。
//     ⚠ 同理，若上机发现"谁对应谁"根本不是前后/左右/自转 ⇒ 改的是**下面这四行映射**，
//       结构不动（用例①已经把它钉成"恰一个关节动"，换轴就是换那四行）。
//
// ---- 入参数组次序（★ Task 2 接线前【先读这一行】）----
//     `refStylus` / `curStylus` = **{Rx, Ry, Rz}** —— 即 `appState.stylusOrient` 的
//     (x, y, z) 三个分量（度）。出处：`core/AppState.h` 的字段注释
//     「笔杆姿态 ZYX Euler (Rx,Ry,Rz in degrees)」+ `haptic/HapticCallback.cpp` 的
//     `[0]=rx_deg · [1]=ry_deg · [2]=rz_deg` 三行赋值。
//     ⚠ 次序**不是** J4/J5/J6 的次序、也不是"按名字首字母"，而下面的映射是**错开**的
//       （out[3]←[0] · out[4]←[2] · out[5]←[1]）⇒ **本接口对索引敏感**。灌错次序的
//       后果是"前后摆变成了左右摆"，而**结构层用例①(b)(c) 会红**（它们就是为此写的）。
//
// ---- 管线（与简报 Step 3 逐条对应）----
//     笔杆偏移 Δ_i = curStylus[i] − refStylus[i]                 （度，逐轴）
//   ① 逐轴死区   |Δ_i| >= `Config::ORIENT_DEADZONE_DEG` 才放行，否则该轴归 0
//   ② 逐轴符号   Δ_i 乘 `Config::BTN2_J*_SIGN`
//   ③ 偏移限幅   关节增量**逐关节**夹到 ±`Config::ORIENT_MAX_OFFSET_DEG`
//   ④ 一一对应   加到参照上：out[3] ← Rx · out[4] ← Rz · out[5] ← Ry
//                out[0..2] = ref[0..2]（无条件，见下）
//
// ⚠⚠ 【单位变了 —— 本段是全文最要紧的一条】上面两个常数**沿用现有名字**，但在这里它们
//   度量的**不再是末端姿态的角度**：
//     · `ORIENT_MAX_OFFSET_DEG`（150°）现在夹的是 `out[i] − refJoints[i]`，即**关节增量**；
//     · `ORIENT_DEADZONE_DEG`（0.05°）现在门的是**笔杆的逐轴偏移**（与旧路径同一个量 ✓，
//       不是关节增量）。
//   ⇒ 150° 对"末端姿态相对起始别转太多"是个保守值，对**关节**则宽松得多（J4/J5/J6 的量程
//     本就在 ±360 量级，见 `Docs/机械臂资料/Dobot CR3机械臂参数文档.md`）。这个数**没有出处**
//     （与 `SAFE_R*` 同一类欠账），取的是"先沿用、上机再看"⇒ Task 3 若觉得幅度不合适，
//     改常数即可，**改的是这一处语义**，结构不动。
//   ⚠ 限幅夹的是**增量**，不是**绝对关节角**：本函数不知道关节量程，也不做量程检查
//     （那是 Task 2 的 `SafetyPredictor` 位置门 + 机械臂自身的限位该管的事）。
//
// ⚠ 【死区为什么在这里、又为什么与 RelayCore 里那一道不冲突】RelayCore 的姿态块里已经有
//   一道 `axisGate`（同一个常数、同一个 `>=` 语义 —— 本文件逐字照抄它），Task 2 接线时会
//   把**已过门**的偏移传进来。两道叠加是**幂等**的（过了门的值再过一次还是它，被归零的
//   还是 0）⇒ 无害。之所以仍在函数内保留一道：这个函数必须**自己成立** ——
//   本文件的用例就是直接喂原始偏移的（简报 Step 1 的④）。
//
// ⚠ 【本函数不施加逐轴增益】计划架构里那一环（"…→ 增益 →…"）**没有**落在这里。
//   这是一个【明确记账的取舍】，不是漏掉：
//     · 现有唯一的姿态增益 `Config::ORIENT_GAIN` 在自己的注释里写明**只作用于旧路径**；
//     · 本文件今天就是 **1:1**（笔杆转 θ° ⇒ 关节转 θ°），与 `ORIENT_GAIN = 1.0` 等效
//       ⇒ **行为上无差别**；
//     · 更要紧的是：在 `= 1.0` 时"乘 1.0"与"不乘"**任何用例都区分不了** ⇒ 那会是一行
//       **没有负对照的乘法**（本仓最怕的假绿）。
//   ⇒ "要不要增益、取多少"是 Task 3 上机手感的事；届时**新开一个常数**（如
//     `BTN2_JOINT_GAIN`），**别复用** `ORIENT_GAIN`（那个语义是末端姿态的）。
//
// ⚠ 【没有位置入参】四个入参里没有任何位置分量 ⇒ 平移在**结构上**进不来 —— 这是
//   "笔杆平移时机械臂不动"的第一道保证（第二道在 RelayCore 的姿态/关节块里）。
//   ⚠ 这是**编译期**性质，运行期测不出来 ⇒ 由 test_button2_joint.cpp ③ 用一个
//     **函数指针类型**钉住（签名一变就编译不过）。
//
// ⚠ NaN/Inf 契约：`refStylus` / `curStylus` 里**任一**分量非有限 ⇒ 返回 `refJoints`
//   （= 关节不动，臂原地保持）。与 `button2OrientationTarget` 的同类守卫一致。
//   ⚠ 但**若 `refJoints` 自己非有限，本函数会把那个非有限值原样传出去** —— 它**不**保证
//     "返回值一定有限"：那一刻没有安全的兜底可退（0 是一个真实关节角，机械臂会真的转过去），
//     那一层只能由调用者负责（`refJoints` 抄自 `app.robotActualPose.j1..j6`，它若已是 NaN，
//     说明机器人状态本身已经坏了）。该行为被用例⑥钉住（断言的是**现状**，且是**刻意**的现状）。
void button2JointTarget(const double refJoints[6],
                        const double refStylus[3],
                        const double curStylus[3],
                        double outJoints[6]);

// ============================================================================
//  接线层的两条纯判据（2026-09-23 Task 2 修复轮：从 RelayCore.cpp **抽出来**）
// ============================================================================
//
// 【为什么要抽】`RelayCore.cpp` **不被任何测试编译** ⇒ 修复轮（复审 1×Critical + 3×Important
//   + 2×Minor）新加的三条判据**一条自动化用例都没有**，只能靠人读 + 上机。而其中两条
//   **本来就是纯算术**（不碰 Win32、不碰 socket、不碰 appState）⇒ 抽到这里，由
//   `tests/test_button2_joint.cpp` 直接喂入参。本文件就是"这条逻辑的受测之家"。
//
// ⚠⚠ 【这一抽**不改变**任何行为，也**不改变**"接线有没有接对"的可验证性】
//   1) 判据、次序、夹取方向、累加点**逐字照抄**原处（见各自的注释与用例）；
//   2) **控制流留在调用方**：三处 `return`（本帧不下发）是流程不是算术 ⇒ 抽出来的只有算术；
//   3) 接线层（`RelayCore.cpp` 里"什么时候调、返回值怎么用"）**仍然没有自动化用例** ⇒
//      仍然只能靠人读 + 上机。**别把"这两条有单测了"读成"接线接对了"** —— 那是两件事。
//
// ⚠ 【依赖变了，必须记账】`isTrustworthyJointRef` 要用 `Kinematics::isWithinJointLimits`
//   ⇒ `Button2Joint.cpp` 现在 `#include "../robot/Kinematics.h"`，而那条链会走到
//   `CoordinateTransform.h` → `<HDU/hduVector.h>` ⇒ **`tests/build_button2_joint_test.bat`
//   从"不需要任何 /I 路径"变成需要 OpenHaptics 那两个 /I，并且要多链接
//   `../robot/Kinematics.cpp`**。那是本次抽取的唯一代价，写在那个 .bat 的注释里（原注释
//   曾断言"本套件不需要 /I" —— 那句现在**是错的**，已就地订正，没有留下）。**函数本身仍然纯**
//   （Kinematics 的 FK/IK 也是纯算术），变的只是**构建图的形状**。

// 参照可信度（复审 I1）：六位**恰好**全 0 **或** 越关节限位 ⇒ 不可信（返回 false）。
//   【场景】`app.robotActualPose.j1..j6` 的初值**全 0**，唯一写入点是 `queryJointAngles` 里
//     `FeedbackParser::parseAngle` 的**成功路径** ⇒ 若 `GetAngle()` 从未解析成功，参照就一直是
//     全 0 ⇒ FK(0,…,0) = (0, −233.3, 756) **过得了位置门** ⇒ `ServoJ(0,…,0)` 会把臂开向模型零位。
//   ⚠ 两个子句**都保留**（少任何一个都会漏掉一整类）：全 0 是"`GetAngle()` 从未成功"的指纹
//     （真机关节零点不会同时精确落在 0.0000），越限位是另一个独立的坏值形态。
//   ⚠⚠ **NaN 不在本函数的覆盖面内，而且是刻意的**：NaN 进 `isWithinJointLimits` 时逐条比较
//     全为 false ⇒ 它**返回 true**（放行）；而"恰好全 0"对 NaN 也为假 ⇒ 本函数对 NaN
//     **返回 true（可信）**。接住 NaN 的是调用方的 **FK 门**（FK(NaN) ⇒ NaN ⇒ 位置入口的
//     第一道守卫 REJECT）—— 那条不在本函数职责内。**这个边界被用例⑬逐字钉住**（断言的
//     是**现状**，且是**刻意**的现状）：别"顺手修好"它 —— 那会是一次**没有负对照**的行为改变。
bool isTrustworthyJointRef(const double ref[6]);

// 逐轴步长限幅（复审 M2）：`out[i] = prev[i] + clamp(desired[i] − prev[i], ±maxStep)`。
//   【形状是从 RPY 路径照抄的】那条路的 `ORIENT_MAX_STEP_DEG` 注释就写着"手一甩不甩飞机器人"；
//     关节路径原来是**没有**这一道 ⇒ 手一甩本帧目标可能一步跨出 ~17.5°（30 Hz ⇒ 525°/s）。
//   ⚠ 夹的是"**本帧要走的量**"再**累加**，不是"把目标夹到 `prev ± maxStep` 就完事" ——
//     两者**逐帧结果相同**，区别在**累加器**：它是"上一帧**已下发**的目标"，由调用方持有
//     （本函数**无状态**：`prev` 由调用方传进来）。大偏移因此在多帧里**慢慢跟上**、
//     **不会被永久截断** —— RPY 路径 2026-09-21 那次改造就是为这个（`Config.h` 里
//     `ORIENT_DEADZONE_DEG` 的历史段）。
//   ⚠ **`out` 允许与 `desired` 同一块内存**（调用方就是原地改写 `j`）：逐轴**先读后写**、
//     每轴只碰自己那一个下标 ⇒ 别名安全。用例⑯(c) 把这个用法钉住。
//   ⚠ NaN：`NaN > maxStep` 与 `NaN < −maxStep` **都为假** ⇒ NaN **原样穿过**（与抽出前逐字
//     一致）。那**不是**本函数该管的事 —— 接住它的是调用方的 FK 门（同 `button2JointTarget`
//     的入参契约）。**别在这里加 isfinite 守卫**：那会是一次没有用例背书的行为改变。
//   ⚠ `maxStep` 传负数是**未定义意图**，本函数**逐字照抄**原写法（先比 `> maxStep`、
//     再比 `< −maxStep`）：负值下先被赋 `maxStep`、再被赋 `−maxStep` ⇒ 结果 = |maxStep|。
//     荒谬，但**与原处一致** —— 没有"顺手修正"（修正就是行为改变，且没有用例会红）。
//     调用方传的是 `Config::ORIENT_MAX_STEP_DEG`。
void clampJointStep(const double prev[6], const double desired[6], double maxStep, double out[6]);
